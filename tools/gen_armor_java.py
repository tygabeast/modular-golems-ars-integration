"""Writes src/main/java/mgarcane/ArmorLayers.java from armor_spec.py + gen_armor.py and aegis_spec.py + gen_aegis.py (so the model and the texture can never disagree)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import armor_spec, gen_armor, aegis_spec, gen_aegis
SETS = [dict(key='arcane', pre='arc_', S=armor_spec, A=gen_armor, C=''), dict(key='aegis', pre='aeg_', S=aegis_spec, A=gen_aegis, C='AEGIS_')]

BASE = {'helmet': 'helmet', 'chestplate': 'chestplate', 'leggings': 'shinguard', 'boots': 'boots'}
BONES = {'head', 'body', 'right_arm', 'left_arm', 'right_leg', 'left_leg', 'right_forearm', 'left_forearm'}
FORE = {'right_forearm': 'right_arm', 'left_forearm': 'left_arm'}


def f(v):
    s = repr(float(v))
    return (s[:-2] if s.endswith('.0') else s) + 'f'


def path_of(bone, name):
    return ([FORE[bone], bone] if bone in FORE else [bone]) + [name]


HEADER = '''package mgarcane;

import dev.xkmc.modulargolems.content.client.armor.GolemEquipmentModels;
import dev.xkmc.modulargolems.content.client.armor.GolemModelPath;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeDeformation;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;
import net.neoforged.api.distmarker.Dist;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.common.EventBusSubscriber;
import net.neoforged.neoforge.client.event.EntityRenderersEvent;

import java.util.List;

/**
 * CLIENT ONLY. The shapes of the Arcane and Aegis armour, drawn on the bones of the Metal Golem model exactly like Modular Golems' own sets.
 * GENERATED by tools/gen_armor_java.py from tools/armor_spec.py and tools/aegis_spec.py (the files the textures are painted from): do not edit by hand.
 * Only registered when Ars Nouveau is present, like the items.
 */
@EventBusSubscriber(modid = MGArcane.MODID, value = Dist.CLIENT)
public final class ArmorLayers {

	private ArmorLayers() {
	}

	private static ModelLayerLocation layer(String name) {
		return new ModelLayerLocation(ResourceLocation.fromNamespaceAndPath("modulargolems", name), "main");
	}
'''


def gen():
    out = [HEADER]
    names = []   # (set, piece) in order
    for st in SETS:
        for p in st['S'].PIECES:
            names.append((st, p))
    def const(st, p): return (st['key'] + '_' + BASE[p]).upper()
    def fn(st, p): return st['key'] + '_' + BASE[p]
    for st, p in names:
        out.append(f'	static final ModelLayerLocation {const(st, p)} = layer("{st["key"]}_{BASE[p]}");')
    out.append('')
    out.append("""	@SubscribeEvent
	public static void onLayers(EntityRenderersEvent.RegisterLayerDefinitions e) {
		if (ArcaneReg.MANTLE == null) return;   // Ars Nouveau absent: no armour exists
""")
    for st, p in names:
        out.append(f'		GolemEquipmentModels.regAndAdd(e, {const(st, p)}, ArmorLayers::{fn(st, p)});')
    out.append('')
    for st, p in names:
        paths = [path_of(bone, st['pre'] + name) for name, bone, pose, boxes in st['S'].BUILD[p]()]
        inner = ', '.join('List.of(' + ', '.join(f'"{x}"' for x in pa) + ')' for pa in paths)
        key = st['C'] + BASE[p].upper()
        out.append(f'		GolemModelPath.register(ArcaneArmor.{key}, new GolemModelPath({const(st, p)}, List.of({inner})));')
    out.append('	}\n')
    for st, p in names:
        S, A = st['S'], st['A']
        W, H = A.SIZE[p]; uv = A.uvs(p)
        out.append(f'	private static LayerDefinition {fn(st, p)}() {{')
        out.append('		MeshDefinition mesh = GolemEquipmentModels.buildGolemBaseLayers();')
        out.append('		PartDefinition root = mesh.getRoot();')
        for b in sorted({bone for _, bone, _, _ in S.BUILD[p]()}):
            if b in FORE: out.append(f'		PartDefinition {b} = root.getChild("{FORE[b]}").getChild("{b}");')
            else: out.append(f'		PartDefinition {b} = root.getChild("{b}");')
        for pi, (name, bone, pose, boxes) in enumerate(S.BUILD[p]()):
            chain = 'CubeListBuilder.create()'
            for bi, (m, x, y, z, w, h, d) in enumerate(boxes):
                u, v = uv[(pi, bi)]
                chain += f'.texOffs({u}, {v}).addBox({f(x)}, {f(y)}, {f(z)}, {f(w)}, {f(h)}, {f(d)}, new CubeDeformation(0f))'
            px, py, pz, rx, ry, rz = pose
            if rx or ry or rz: raise SystemExit('rotated parts are not supported by the verified-signature subset')
            pp = f'PartPose.offset({f(px)}, {f(py)}, {f(pz)})'
            out.append(f'		{bone}.addOrReplaceChild("{st["pre"]}{name}", {chain}, {pp});')
        out.append(f'		return LayerDefinition.create(mesh, {W}, {H});')
        out.append('	}\n')
    out.append('}')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'main', 'java', 'mgarcane', 'ArmorLayers.java')
    open(dst, 'w').write(gen())
    print('wrote', dst)
