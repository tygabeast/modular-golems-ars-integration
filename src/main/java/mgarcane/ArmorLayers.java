package mgarcane;

import dev.xkmc.modulargolems.content.client.armor.GolemEquipmentModels;
import dev.xkmc.modulargolems.content.client.armor.GolemModelPath;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeDeformation;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;
import net.neoforged.api.distmarker.Dist;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.common.EventBusSubscriber;
import net.neoforged.neoforge.client.event.EntityRenderersEvent;

import java.util.List;

/**
 * CLIENT ONLY. The shapes of the Arcane armour, drawn on the bones of the Metal Golem model exactly like Modular Golems' own sets.
 * GENERATED by tools/gen_armor_java.py from tools/armor_spec.py (same file the textures are painted from): do not edit by hand.
 * Only registered when Ars Nouveau is present, like the items.
 */
@EventBusSubscriber(modid = MGArcane.MODID, value = Dist.CLIENT)
public final class ArmorLayers {

	private ArmorLayers() {
	}

	private static ModelLayerLocation layer(String name) {
		return new ModelLayerLocation(ResourceLocation.fromNamespaceAndPath("modulargolems", name), "main");
	}

	static final ModelLayerLocation HELMET = layer("arcane_helmet");
	static final ModelLayerLocation CHESTPLATE = layer("arcane_chestplate");
	static final ModelLayerLocation SHINGUARD = layer("arcane_shinguard");
	static final ModelLayerLocation BOOTS = layer("arcane_boots");

	@SubscribeEvent
	public static void onLayers(EntityRenderersEvent.RegisterLayerDefinitions e) {
		if (ArcaneReg.MANTLE == null) return;   // Ars Nouveau absent: no armour exists

		GolemEquipmentModels.regAndAdd(e, HELMET, ArmorLayers::helmet);
		GolemEquipmentModels.regAndAdd(e, CHESTPLATE, ArmorLayers::chestplate);
		GolemEquipmentModels.regAndAdd(e, SHINGUARD, ArmorLayers::shinguard);
		GolemEquipmentModels.regAndAdd(e, BOOTS, ArmorLayers::boots);

		GolemModelPath.register(ArcaneArmor.HELMET, new GolemModelPath(HELMET, List.of(List.of("head", "arc_hood"), List.of("head", "arc_circlet"), List.of("head", "arc_gem"), List.of("head", "arc_peak"))));
		GolemModelPath.register(ArcaneArmor.CHESTPLATE, new GolemModelPath(CHESTPLATE, List.of(List.of("body", "arc_tunic"), List.of("body", "arc_clasp"), List.of("right_arm", "arc_sleeve"), List.of("right_arm", "arc_cap"), List.of("right_arm", "right_forearm", "arc_cuff"), List.of("left_arm", "arc_sleeve_l"), List.of("left_arm", "arc_cap_l"), List.of("left_arm", "left_forearm", "arc_cuff_l"))));
		GolemModelPath.register(ArcaneArmor.SHINGUARD, new GolemModelPath(SHINGUARD, List.of(List.of("body", "arc_sash"), List.of("body", "arc_tabard"), List.of("body", "arc_buckle"), List.of("right_leg", "arc_hip"), List.of("left_leg", "arc_hip_l"))));
		GolemModelPath.register(ArcaneArmor.BOOTS, new GolemModelPath(BOOTS, List.of(List.of("right_leg", "arc_boot"), List.of("left_leg", "arc_boot_l"))));
	}

	private static LayerDefinition helmet() {
		MeshDefinition mesh = GolemEquipmentModels.buildGolemBaseLayers();
		PartDefinition root = mesh.getRoot();
		PartDefinition head = root.getChild("head");
		head.addOrReplaceChild("arc_hood", CubeListBuilder.create().texOffs(0, 0).addBox(-4.5f, -12.5f, -6f, 9f, 11f, 9f, new CubeDeformation(0f)), PartPose.offset(0f, 0f, 0f));
		head.addOrReplaceChild("arc_circlet", CubeListBuilder.create().texOffs(0, 20).addBox(-5f, -9.5f, -6.5f, 10f, 2f, 10f, new CubeDeformation(0f)), PartPose.offset(0f, 0f, 0f));
		head.addOrReplaceChild("arc_gem", CubeListBuilder.create().texOffs(44, 32).addBox(-1.5f, -10f, -7.5f, 3f, 3f, 1f, new CubeDeformation(0f)), PartPose.offset(0f, 0f, 0f));
		head.addOrReplaceChild("arc_peak", CubeListBuilder.create().texOffs(0, 32).addBox(-3f, -14.5f, -3f, 6f, 2f, 7f, new CubeDeformation(0f)).texOffs(26, 32).addBox(-2f, -16.5f, -0.5f, 4f, 2f, 5f, new CubeDeformation(0f)), PartPose.offset(0f, 0f, 0f));
		return LayerDefinition.create(mesh, 64, 64);
	}

	private static LayerDefinition chestplate() {
		MeshDefinition mesh = GolemEquipmentModels.buildGolemBaseLayers();
		PartDefinition root = mesh.getRoot();
		PartDefinition body = root.getChild("body");
		PartDefinition left_arm = root.getChild("left_arm");
		PartDefinition left_forearm = root.getChild("left_arm").getChild("left_forearm");
		PartDefinition right_arm = root.getChild("right_arm");
		PartDefinition right_forearm = root.getChild("right_arm").getChild("right_forearm");
		body.addOrReplaceChild("arc_tunic", CubeListBuilder.create().texOffs(0, 0).addBox(-9.5f, -2.5f, -6.5f, 19f, 13f, 12f, new CubeDeformation(0f)), PartPose.offset(0f, 0f, 0f));
		body.addOrReplaceChild("arc_clasp", CubeListBuilder.create().texOffs(104, 25).addBox(-2f, -0.5f, -7.5f, 4f, 5f, 1f, new CubeDeformation(0f)), PartPose.offset(0f, 0f, 0f));
		right_arm.addOrReplaceChild("arc_sleeve", CubeListBuilder.create().texOffs(88, 0).addBox(-14.5f, -3f, -3.5f, 6f, 10f, 7f, new CubeDeformation(0f)), PartPose.offset(0f, 0f, 0f));
		right_arm.addOrReplaceChild("arc_cap", CubeListBuilder.create().texOffs(76, 25).addBox(-15f, -4.5f, -4f, 6f, 2f, 8f, new CubeDeformation(0f)), PartPose.offset(0f, 0f, 0f));
		right_forearm.addOrReplaceChild("arc_cuff", CubeListBuilder.create().texOffs(24, 25).addBox(-13.5f, 0.5f, -6.5f, 5f, 7f, 7f, new CubeDeformation(0f)), PartPose.offset(0f, 0f, 0f));
		left_arm.addOrReplaceChild("arc_sleeve_l", CubeListBuilder.create().texOffs(62, 0).addBox(8.5f, -3f, -3.5f, 6f, 10f, 7f, new CubeDeformation(0f)), PartPose.offset(0f, 0f, 0f));
		left_arm.addOrReplaceChild("arc_cap_l", CubeListBuilder.create().texOffs(48, 25).addBox(9f, -4.5f, -4f, 6f, 2f, 8f, new CubeDeformation(0f)), PartPose.offset(0f, 0f, 0f));
		left_forearm.addOrReplaceChild("arc_cuff_l", CubeListBuilder.create().texOffs(0, 25).addBox(8.5f, 0.5f, -6.5f, 5f, 7f, 7f, new CubeDeformation(0f)), PartPose.offset(0f, 0f, 0f));
		return LayerDefinition.create(mesh, 128, 64);
	}

	private static LayerDefinition shinguard() {
		MeshDefinition mesh = GolemEquipmentModels.buildGolemBaseLayers();
		PartDefinition root = mesh.getRoot();
		PartDefinition body = root.getChild("body");
		PartDefinition left_leg = root.getChild("left_leg");
		PartDefinition right_leg = root.getChild("right_leg");
		body.addOrReplaceChild("arc_sash", CubeListBuilder.create().texOffs(0, 0).addBox(-5.5f, 9.5f, -4f, 11f, 3f, 8f, new CubeDeformation(0f)), PartPose.offset(0f, 0f, 0f));
		body.addOrReplaceChild("arc_tabard", CubeListBuilder.create().texOffs(26, 11).addBox(-3f, 12f, -4.75f, 6f, 6f, 1f, new CubeDeformation(0f)), PartPose.offset(0f, 0f, 0f));
		body.addOrReplaceChild("arc_buckle", CubeListBuilder.create().texOffs(40, 11).addBox(-1f, 9.5f, -5f, 2f, 2f, 1f, new CubeDeformation(0f)), PartPose.offset(0f, 0f, 0f));
		right_leg.addOrReplaceChild("arc_hip", CubeListBuilder.create().texOffs(0, 11).addBox(-4f, -9f, -3.5f, 7f, 5f, 6f, new CubeDeformation(0f)), PartPose.offset(0f, 0f, 0f));
		left_leg.addOrReplaceChild("arc_hip_l", CubeListBuilder.create().texOffs(38, 0).addBox(-4f, -9f, -3.5f, 7f, 5f, 6f, new CubeDeformation(0f)), PartPose.offset(0f, 0f, 0f));
		return LayerDefinition.create(mesh, 64, 32);
	}

	private static LayerDefinition boots() {
		MeshDefinition mesh = GolemEquipmentModels.buildGolemBaseLayers();
		PartDefinition root = mesh.getRoot();
		PartDefinition left_leg = root.getChild("left_leg");
		PartDefinition right_leg = root.getChild("right_leg");
		right_leg.addOrReplaceChild("arc_boot", CubeListBuilder.create().texOffs(28, 0).addBox(-4f, 7.5f, -3.5f, 7f, 5f, 7f, new CubeDeformation(0f)), PartPose.offset(0f, 0f, 0f));
		left_leg.addOrReplaceChild("arc_boot_l", CubeListBuilder.create().texOffs(0, 0).addBox(-4f, 7.5f, -3.5f, 7f, 5f, 7f, new CubeDeformation(0f)), PartPose.offset(0f, 0f, 0f));
		return LayerDefinition.create(mesh, 64, 32);
	}

}
